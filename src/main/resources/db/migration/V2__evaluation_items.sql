-- 人事評価の項目と、日次メモとの紐付け。
--
-- 評価は期末に材料を探しても作れない。期中に「材料が無い項目」が見えるようにするため、
-- 日次メモを書くときに評価項目を選べるようにする。

create table evaluation_item (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    display_order integer      not null,
    active        boolean      not null,
    constraint uk_evaluation_item_name unique (name)
);

-- 1 件のメモが複数の項目に効くことがあるため多対多にする
create table daily_log_evaluation_item (
    daily_log_id       bigint not null,
    evaluation_item_id bigint not null,
    constraint fk_daily_log_evaluation_item_log
        foreign key (daily_log_id) references daily_log (id),
    constraint fk_daily_log_evaluation_item_item
        foreign key (evaluation_item_id) references evaluation_item (id)
);

create index idx_daily_log_evaluation_item_log
    on daily_log_evaluation_item (daily_log_id);
