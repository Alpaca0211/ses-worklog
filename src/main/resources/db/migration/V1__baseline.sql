-- 現在のスキーマをベースラインとして固定したもの。
--
-- これ以降のスキーマ変更は V2 以降の SQL を追加する形で行う。
-- ddl-auto は validate にしてあるため、エンティティとこのスキーマがずれると起動時に落ちる。
--
-- 既存のデータベースには baseline-on-migrate により「適用済み」として記録され、
-- このファイルは実行されない。新規のデータベースでのみ実行される。

create table forbidden_term (
    id          bigint generated by default as identity primary key,
    term        varchar(200) not null,
    replacement varchar(200) not null,
    category    varchar(20)  not null,
    enabled     boolean      not null,
    created_at  timestamp(6) with time zone not null,
    constraint uk_forbidden_term_term unique (term),
    constraint ck_forbidden_term_category
        check (category in ('CLIENT', 'SYSTEM', 'PERSON', 'PROJECT', 'ORG', 'OTHER'))
);

create table technology (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    category      varchar(30)  not null,
    display_order integer      not null,
    active        boolean      not null,
    constraint uk_technology_name unique (name),
    constraint ck_technology_category
        check (category in ('LANGUAGE_FRAMEWORK', 'OS_TOOL'))
);

create table task_type (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    display_order integer      not null,
    active        boolean      not null,
    constraint uk_task_type_name unique (name)
);

create table performance_template (
    id            bigint generated by default as identity primary key,
    text          varchar(500) not null,
    display_order integer      not null
);

create table project (
    id                   bigint generated by default as identity primary key,
    name                 varchar(100) not null,
    display_order        integer      not null,
    active               boolean      not null,
    industry             varchar(50),
    public_description   varchar(200),
    overview             varchar(2000),
    team_composition     varchar(200),
    project_scale        varchar(200),
    environment          varchar(100),
    start_date           date,
    end_date             date,
    career_merge_into_id bigint,
    constraint uk_project_name unique (name),
    constraint fk_project_career_merge_into
        foreign key (career_merge_into_id) references project (id)
);

create table project_technology (
    project_id    bigint not null,
    technology_id bigint not null,
    constraint fk_project_technology_project
        foreign key (project_id) references project (id),
    constraint fk_project_technology_technology
        foreign key (technology_id) references technology (id)
);

create table work_entry (
    id         bigint generated by default as identity primary key,
    work_date  date   not null,
    project_id bigint not null,
    workstream varchar(200),
    targets    varchar(500),
    created_at timestamp(6) with time zone not null,
    constraint fk_work_entry_project
        foreign key (project_id) references project (id)
);

create index idx_work_entry_date on work_entry (work_date);

-- 作業種別は 1 件の記録に複数付く。出力時の連結順を保つため position を持つ
create table work_entry_task_type (
    work_entry_id bigint  not null,
    task_type_id  bigint  not null,
    "position"    integer not null,
    primary key (work_entry_id, "position"),
    constraint fk_work_entry_task_type_entry
        foreign key (work_entry_id) references work_entry (id),
    constraint fk_work_entry_task_type_task_type
        foreign key (task_type_id) references task_type (id)
);

-- 生ログは AES-256-GCM の暗号文を格納するため、平文より長くなる
create table daily_log (
    id           bigint generated by default as identity primary key,
    work_date    date          not null,
    raw_text     varchar(20000) not null,
    masked_text  varchar(10000) not null,
    output_text  varchar(10000) not null,
    status       varchar(30)   not null,
    masked_count integer       not null,
    risk_hints   varchar(2000),
    created_at   timestamp(6) with time zone not null,
    constraint ck_daily_log_status
        check (status in ('MASKED_ONLY', 'ABSTRACTED', 'ABSTRACTED_REMASKED'))
);

create index idx_daily_log_work_date on daily_log (work_date);

-- year / month は多くの DB で予約語のため列名に使わない
create table past_weekly_report (
    id            bigint generated by default as identity primary key,
    report_year   integer not null,
    report_month  integer not null,
    week_num      integer not null,
    performance   varchar(20000),
    communication varchar(20000),
    learned       varchar(20000),
    imported_at   timestamp(6) with time zone not null,
    constraint uk_past_weekly_report_week unique (report_year, report_month, week_num)
);
